/**
 * Builds a standalone HTML page from src/ that runs the real UI in a normal
 * browser (or jsdom) without Apps Script:
 *  - expands <?!= include('Name'); ?> like HtmlService does;
 *  - replaces google.script.run with a stub that calls the real Logic.js
 *    functions on fixture data, mirroring the endpoints in Code.js.
 *
 * Options (also readable from the page URL, e.g. /?today=2026-10-01&scenario=error:NO_PERMISSION):
 *   today     'YYYY-MM-DD' used as "today" in Lima (default: real today in Lima)
 *   scenario  'ok' | 'empty' | 'error:<CODE>'
 *   delay     simulated server latency in ms
 */
const fs = require('fs');
const path = require('path');
const { makeFixtures } = require('./fixtures');

const SRC = path.join(__dirname, '..', 'src');

function limaToday() {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Lima' }).format(new Date());
}

function read(name) {
  return fs.readFileSync(path.join(SRC, name), 'utf8');
}

function stubScript(opts) {
  const fixtures = makeFixtures(opts.today);
  return `<script>
${read('Logic.js')}
{
  const params = new URLSearchParams(location.search);
  const TODAY = params.get('today') || ${JSON.stringify(opts.today)};
  const SCENARIO = params.get('scenario') || ${JSON.stringify(opts.scenario || 'ok')};
  const DELAY = Number(params.get('delay') || ${Number(opts.delay) || 0});
  const FIXTURES = ${JSON.stringify(fixtures)};
  let settings = null;
  try { settings = JSON.parse(localStorage.getItem('preview-settings')); } catch (e) {}

  const endpoints = {
    getDashboard(month, forceRefresh) {
      if (SCENARIO.indexOf('error:') === 0) {
        const code = SCENARIO.slice(6);
        return { ok: false, error: { code: code, message: 'Simulated ' + code + ' error (local preview).' } };
      }
      const src = SCENARIO === 'empty' ? { expenses: [FIXTURES.expenses[0]], budgets: FIXTURES.budgets } : FIXTURES;
      const parsed = parseExpenses(src.expenses);
      const d = buildDashboard({
        expenses: parsed.expenses, invalid: parsed.invalid,
        budgets: parseBudgets(src.budgets), income: findIncome(FIXTURES.framework)
      }, { month: month, today: TODAY, settings: settings });
      d.loadedAt = new Date().toISOString();
      d.fromCache = !forceRefresh;
      return { ok: true, data: d };
    },
    saveSettings(input) {
      settings = sanitizeSettings(input);
      try { localStorage.setItem('preview-settings', JSON.stringify(settings)); } catch (e) {}
      return { ok: true, data: settings };
    }
  };

  function runner(onOk, onFail) {
    const r = {
      withSuccessHandler: f => runner(f, onFail),
      withFailureHandler: f => runner(onOk, f)
    };
    Object.keys(endpoints).forEach(name => {
      r[name] = (...args) => {
        setTimeout(() => {
          try {
            // Round-trip through JSON like google.script.run does.
            const res = JSON.parse(JSON.stringify(endpoints[name].apply(null, args)));
            if (onOk) onOk(res);
          } catch (e) {
            if (onFail) onFail(e); else console.error(e);
          }
        }, DELAY);
      };
    });
    return r;
  }
  window.google = { script: { get run() { return runner(null, null); } } };
}
</script>`;
}

function buildPreviewHtml(opts) {
  opts = Object.assign({ scenario: 'ok', delay: 0 }, opts);
  if (!opts.today) opts.today = limaToday();
  const html = read('Index.html').replace(/<\?!=\s*include\('([^']+)'\);?\s*\?>/g, (_, name) =>
    (name === 'Client' ? stubScript(opts) : '') + read(name + '.html'));
  if (/<\?/.test(html)) throw new Error('Unsupported template scriptlet left in Index.html');
  return '<!-- Generated by dev/build-preview.js - local preview with fake data -->\n' + html;
}

module.exports = { buildPreviewHtml, limaToday };
